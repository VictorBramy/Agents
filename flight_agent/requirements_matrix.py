def get_requirements_matrix() -> Dict[str, Any]:
    """Returns the full requirements matrix with summary statistics."""
    total = len(USER_REQUIREMENTS)
    passed = sum(1 for r in USER_REQUIREMENTS if r.get("status") == "PASSED")
    compliance_rate = round((passed / total) * 100, 1) if total > 0 else 100.0

    return {
        "timestamp": datetime.now().isoformat(),
        "total_requirements": total,
        "passed_requirements": passed,
        "compliance_score": compliance_rate,
        "status_summary": f"{passed}/{total} דרישות אומתו בהצלחה ({compliance_rate}%)",
        "requirements": USER_REQUIREMENTS
    }

def save_audit_results(audit_report: Dict[str, Any]) -> None:
    """Saves the latest audit run to the persistent json file."""
    try:
        os.makedirs(os.path.dirname(AUDIT_LOG_FILE), exist_ok=True)
        with open(AUDIT_LOG_FILE, "w", encoding="utf-8") as f:
            json.dump(audit_report, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"[Requirements Matrix Save Error]: {e}")

def load_latest_audit_results() -> Optional[Dict[str, Any]]:
    """Loads the latest audit run from the persistent json file."""
    if os.path.exists(AUDIT_LOG_FILE):
        try:
            with open(AUDIT_LOG_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    return None
